CREATE TABLE IF NOT EXISTS msg (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  dev TEXT NOT NULL,
  box TEXT NOT NULL,
  blob TEXT NOT NULL,
  ts INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS msg_dev ON msg (dev, box, id);
CREATE INDEX IF NOT EXISTS msg_ts ON msg (ts);
CREATE TABLE IF NOT EXISTS rl (
  k TEXT NOT NULL,
  win INTEGER NOT NULL,
  n INTEGER NOT NULL,
  PRIMARY KEY (k, win)
);
